"""
gateway/adapters/schemas.py
===========================
Standardized OpenAI-compatible Chat Completion Schemas.

Enforces strict type safety across all upstream providers (Groq, Gemini, OpenAI).
Every incoming request and outgoing response is normalized to this canonical schema.
"""
from decimal import Decimal
from typing import List, Literal, Optional
from uuid import uuid4
import time

from pydantic import BaseModel, Field


class ChatMessage(BaseModel):
    """Normalized chat message structure."""

    role: Literal["system", "user", "assistant"] = Field(
        ...,
        description="The role of the message author.",
        examples=["user"],
    )
    content: str = Field(
        ...,
        description="The contents of the message.",
        examples=["Explain quantum computing in one sentence."],
    )


class ChatCompletionRequest(BaseModel):
    """Normalized inbound chat completion request."""

    model: str = Field(
        ...,
        description="Target model identifier (e.g. 'groq/llama-3.1-8b', 'openai/gpt-4o-mini', 'google/gemini-1.5-flash', 'mock/test-model').",
        examples=["groq/llama-3.1-8b"],
    )
    strategy: Optional[str] = Field(
        default=None,
        description="Optional routing strategy override (e.g. 'cost_optimized', 'latency_optimized', 'quality_optimized').",
    )
    messages: List[ChatMessage] = Field(
        ...,
        min_length=1,
        description="List of messages comprising the conversation so far.",
    )
    temperature: Optional[float] = Field(
        default=0.7,
        ge=0.0,
        le=2.0,
        description="Sampling temperature between 0 and 2.",
    )
    max_tokens: Optional[int] = Field(
        default=1024,
        gt=0,
        description="Maximum number of tokens to generate.",
    )
    top_p: Optional[float] = Field(
        default=1.0,
        ge=0.0,
        le=1.0,
        description="Nucleus sampling threshold.",
    )
    stream: bool = Field(
        default=False,
        description="Whether to stream back partial progress using Server-Sent Events.",
    )


class TokenUsage(BaseModel):
    """Detailed token consumption breakdown."""

    prompt_tokens: int = Field(..., ge=0, description="Tokens consumed by the prompt.")
    completion_tokens: int = Field(..., ge=0, description="Tokens generated in the response.")
    total_tokens: int = Field(..., ge=0, description="Total tokens consumed.")


class ChatCompletionChoice(BaseModel):
    """A single completion candidate generated by the provider."""

    index: int = Field(0, description="Candidate choice index.")
    message: ChatMessage = Field(..., description="Generated message object.")
    finish_reason: Optional[str] = Field("stop", description="Reason model stopped generating.")


class ChatCompletionResponse(BaseModel):
    """Normalized outbound chat completion response."""

    id: str = Field(
        default_factory=lambda: f"chatcmpl-{uuid4().hex[:12]}",
        description="Unique completion identifier.",
    )
    object: str = Field("chat.completion", description="Object type.")
    created: int = Field(
        default_factory=lambda: int(time.time()),
        description="Unix timestamp when response was generated.",
    )
    model: str = Field(..., description="Canonical model that handled the request.")
    provider: str = Field(..., description="LLM provider that executed the request.")
    choices: List[ChatCompletionChoice] = Field(..., description="List of generated choices.")
    usage: TokenUsage = Field(..., description="Token usage details.")
    cost_usd: Decimal = Field(
        default=Decimal("0.00000000"),
        description="Accurate calculated FinOps cost in USD for this call.",
    )
    latency_ms: float = Field(
        ...,
        description="Total round-trip latency to the upstream provider in milliseconds.",
    )
